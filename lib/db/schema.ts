/**
 * Table definitions for the Firestore-backed data layer.
 *
 * Generated once from the Supabase pg_dump (schema.sql + supabase/migrations) when the
 * project moved to Firebase, and maintained by hand from here on. Each entry mirrors the
 * old Postgres table so the query layer can keep Postgres semantics on top of Firestore:
 *   - columns: value type (used to coerce writes and filter values) and column default
 *   - pk: primary key column, used as the Firestore document id
 *   - unique: unique constraints (enforced with sentinel docs, see mutations.ts)
 *   - fks: relations used for embedded selects (`hotel:hotels(name)`) and ON DELETE rules
 *   - parent: the table is stored as a subcollection of its parent row, e.g. room_types live at
 *     hotels/{hotel_id}/room_types/{id} (see layout.ts). The parent FK must be NOT NULL and
 *     CASCADE (or RESTRICT/NO ACTION) so deleting a parent never leaves orphaned subcollections.
 *
 * Row-level access rules live in policies.ts.
 */

export type ColumnType =
  | 'uuid' | 'text' | 'int' | 'numeric' | 'bool' | 'date'
  | 'timestamptz' | 'timestamp' | 'time' | 'json' | 'text[]'

export type ColumnDefault = string | number | boolean | unknown[] | Record<string, unknown> | { fn: 'uuid' | 'now' }

export interface ColumnDef {
  type: ColumnType
  default?: ColumnDefault
  /** Computed by a hook in hooks.ts; writes to it are ignored (Postgres GENERATED column) */
  generated?: boolean
}

export interface ForeignKey {
  name: string
  column: string
  refTable: string
  refColumn: string
  onDelete: 'cascade' | 'set_null' | 'restrict' | 'no_action'
}

export interface TableDef {
  pk: string
  parent?: { table: string; column: string }
  columns: Record<string, ColumnDef>
  unique: string[][]
  fks: ForeignKey[]
}

